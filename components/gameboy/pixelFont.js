export const GLYPH_COLS = 5;
export const GLYPH_ROWS = 8; // 7 for caps + 1 descender row
export const CAP_ROWS = 7;
const ADVANCE = GLYPH_COLS + 1; // one pixel of tracking

/** Width of `text` in viewBox units at pixel size `px` (no trailing tracking). */
export function textWidth(text, px) {
  if (!text.length) return 0;
  return (text.length * ADVANCE - 1) * px;
}

/** SVG path data drawing `text` with its top-left corner at (x, y), one `px` square per pixel. */
export function textPath(text, x, y, px) {
  let d = "";
  for (let i = 0; i < text.length; i++) {
    const rows = GLYPHS[text[i]] ?? GLYPHS[text[i].toUpperCase()];
    if (!rows) continue;
    const gx = x + i * ADVANCE * px;
    for (let r = 0; r < GLYPH_ROWS; r++) {
      const row = rows[r] ?? ".....";
      for (let c = 0; c < GLYPH_COLS; c++) {
        if (row[c] === "#")
          d += `M${gx + c * px} ${y + r * px}h${px}v${px}h-${px}z`;
      }
    }
  }
  return d;
}
