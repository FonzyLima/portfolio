#!/usr/bin/env node
/**
 * Renders the partner's later stages (scripts/partner/sprites.mjs) into
 * components/gameboy/partnerArt.js (one <path> per colour, in the Game Boy
 * viewBox, feet on Charmander's ground line) and public/gameboy/<stage>-console.svg
 * (standalone copies for the DevTools greeting, like scripts/console-sprite.mjs).
 *
 * Usage: node scripts/partner-art.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { BAKED, FILLS, FLAME, PX, STAGES } from "./partner/sprites.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_JSX = path.join(ROOT, "components/gameboy/partnerArt.js");
const PAD = 4;
const r2 = (n) => Math.round(n * 100) / 100;

// Charmander's body centre column (the head/body blob, not the flame) keeps the
// evolutions standing where it stands.
const { x0: MON_X0, y1: GROUND } = BAKED.geo.mon;
const BAKED_CENTRE = 35;

function paths(rows, x0, y0, filter) {
  const byColour = new Map();
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const l = row[x];
      if (l === "." || !filter(l)) { x++; continue; }
      let w = 1;
      while (row[x + w] === l) w++;
      if (!FILLS[l]) throw new Error(`Unknown letter "${l}"`);
      byColour.set(l, (byColour.get(l) ?? "") + `M${r2(x0 + x * PX)} ${r2(y0 + y * PX)}h${r2(w * PX)}v${r2(PX)}h-${r2(w * PX)}z`);
      x += w;
    }
  });
  return [...byColour].map(([l, d]) => ({ fill: FILLS[l], d }));
}

const stages = STAGES.map((stage, i) => {
  if (!stage) return null;
  const W = Math.max(...stage.rows.map((r) => r.length)), H = stage.rows.length;
  const centre = stage.centre ?? W / 2;
  const x0 = r2(MON_X0 + (BAKED_CENTRE - centre) * PX), y0 = r2(GROUND - H * PX);
  const box = { x0, y0, x1: r2(x0 + W * PX), y1: r2(GROUND) };
  const body = paths(stage.rows, x0, y0, (l) => !FLAME.has(l));
  const flame = paths(stage.rows, x0, y0, (l) => FLAME.has(l));
  const svgPaths = (ps) => ps.map((p) => `<path fill="${p.fill}" d="${p.d}"/>`).join("");
  const viewBox = [box.x0 - PAD, box.y0 - PAD, box.x1 - box.x0 + 2 * PAD, box.y1 - box.y0 + 2 * PAD].map(r2).join(" ");
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" shape-rendering="crispEdges" aria-label="${stage.name[0]}${stage.name.slice(1).toLowerCase()}">${svgPaths(body)}<g data-layer="mon-flame">${svgPaths(flame)}</g></svg>\n`;
  const out = path.join(ROOT, `public/gameboy/${stage.slug}-console.svg`);
  fs.writeFileSync(out, svg);
  console.log(`wrote ${path.relative(ROOT, out)} (${svg.length} bytes) box ${JSON.stringify(box)} ${W}x${H}px`);
  const jsxPaths = (ps, indent) => ps.map((p) => `${indent}<path fill="${p.fill}" d="${p.d}" />`).join("\n");
  const component = `Stage${i}`;
  return { i, name: stage.name, slug: stage.slug, box, jsx: `/** ${stage.name[0]}${stage.name.slice(1).toLowerCase()} back sprite. Contains <g data-layer="mon-flame">. */
export function ${component}Art() {
  return (
    <>
${jsxPaths(body, "      ")}
      <g data-layer="mon-flame">
${jsxPaths(flame, "        ")}
      </g>
    </>
  );
}` };
});

const jsx = `// AUTO-GENERATED by scripts/partner-art.mjs from scripts/partner/sprites.mjs. Do not edit by hand.
// The partner's later stages, drawn in the Game Boy viewBox beside the baked
// Charmander (components/gameboy/gameboyArt.js). Stage 0 is Charmander itself.
import { GEOMETRY, MonArt } from "./gameboyArt";

export const STAGE_NAMES = ${JSON.stringify(["CHARMANDER", ...stages.filter(Boolean).map((s) => s.name)])};
export const STAGE_SLUGS = ${JSON.stringify(["charmander", ...stages.filter(Boolean).map((s) => s.slug)])};

/** Bounding box of each stage's sprite (viewBox units). */
export const STAGE_BOXES = [GEOMETRY.mon, ${stages.filter(Boolean).map((s) => JSON.stringify(s.box)).join(", ")}];

/** Union of the stage boxes: the sprite area whatever the stage. */
export const PARTNER_BOX = {
  x0: Math.min(...STAGE_BOXES.map((b) => b.x0)),
  y0: Math.min(...STAGE_BOXES.map((b) => b.y0)),
  x1: Math.max(...STAGE_BOXES.map((b) => b.x1)),
  y1: Math.max(...STAGE_BOXES.map((b) => b.y1)),
};

${stages.filter(Boolean).map((s) => s.jsx).join("\n\n")}

/** The art for each stage, indexed like STAGE_NAMES. */
export const STAGE_ARTS = [MonArt, ${stages.filter(Boolean).map((s) => `Stage${s.i}Art`).join(", ")}];
`;
fs.writeFileSync(OUT_JSX, jsx);
console.log(`wrote ${path.relative(ROOT, OUT_JSX)} (${(jsx.length / 1024).toFixed(1)} KB)`);
