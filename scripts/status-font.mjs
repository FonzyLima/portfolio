#!/usr/bin/env node
/**
 * Writes components/gameboy/statusFont.js: the "Pokemon Pixel Font" glyphs a
 * nickname or level can use, pre-scaled to the size of the baked
 * "CHARMANDER♂ Lv5" in the Game Boy status box (8 font pixels over 19.67
 * viewBox units tall, 6 over 11.95 wide), so components/gameboy/StatusName.js
 * can draw any name in the same font.
 *
 * Needs the font at ~/Library/Fonts/pokemon_pixel_font.ttf and opentype.js,
 * which isn't a dependency of the site:
 *   npm i --no-save opentype.js@1.3.4 && node scripts/status-font.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const FONT = path.join(process.env.HOME, "Library/Fonts/pokemon_pixel_font.ttf");
const OUT = path.join(ROOT, "components/gameboy/statusFont.js");
// Font units (1024/em, 64 per font pixel) -> viewBox units, measured off the baked text.
const SX = 1.992 / 64;
const SY = 2.459 / 64;
const CHARS = [..."ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789 .-'!?v"];

const font = opentype.loadSync(FONT);
const r = (n) => Math.round(n * 100) / 100;
const glyphs = {};
for (const ch of CHARS) {
  const g = font.charToGlyph(ch);
  let d = "";
  for (const c of g.getPath(0, 0, 1024).commands) {
    if (c.type === "M" || c.type === "L") d += `${c.type}${r(c.x * SX)} ${r(c.y * SY)}`;
    else if (c.type === "Q") d += `Q${r(c.x1 * SX)} ${r(c.y1 * SY)} ${r(c.x * SX)} ${r(c.y * SY)}`;
    else if (c.type === "C") d += `C${r(c.x1 * SX)} ${r(c.y1 * SY)} ${r(c.x2 * SX)} ${r(c.y2 * SY)} ${r(c.x * SX)} ${r(c.y * SY)}`;
    else if (c.type === "Z") d += "Z";
  }
  glyphs[ch] = [r(g.advanceWidth * SX), d];
}

const out = `// Generated by scripts/status-font.mjs. Do not edit by hand.
// The "Pokemon Pixel Font" glyphs used by the baked "CHARMANDER♂ Lv5" in the
// Game Boy status box, pre-scaled to that text's pixel size (1.99 x 2.46
// viewBox units per font pixel) and sitting on the baseline at y=0. Only the
// characters a nickname or level can use. Each entry is [advance, path].
export const STATUS_GLYPHS = ${JSON.stringify(glyphs)};

const COORDS = /([MLQC])((?:-?[\\d.]+ -?[\\d.]+ ?)+)/g;

/** Path data for \`text\` with its baseline's left end at (x, y). Unknown characters advance like a space. */
export function statusTextPath(text, x, y) {
  let d = "";
  let cx = x;
  for (const ch of text) {
    const [adv, path] = STATUS_GLYPHS[ch] ?? STATUS_GLYPHS[" "];
    if (path)
      d += path.replace(COORDS, (_, cmd, nums) => {
        const v = nums.trim().split(" ").map(Number);
        let o = cmd;
        for (let i = 0; i < v.length; i += 2)
          o += \`\${(v[i] + cx).toFixed(2)} \${(v[i + 1] + y).toFixed(2)}\${i + 2 < v.length ? " " : ""}\`;
        return o;
      });
    cx += adv;
  }
  return d;
}

/** Advance width of \`text\`. */
export function statusTextWidth(text) {
  let w = 0;
  for (const ch of text) w += (STATUS_GLYPHS[ch] ?? STATUS_GLYPHS[" "])[0];
  return w;
}
`;
fs.writeFileSync(OUT, out);
console.log(`wrote ${path.relative(ROOT, OUT)} (${Object.keys(glyphs).length} glyphs, ${(out.length / 1024).toFixed(1)} KB)`);
